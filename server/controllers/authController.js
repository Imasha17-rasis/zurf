const User = require('../models/User');
const { generateToken } = require('../middleware/authMiddleware');
const uploadToCloudinary = require('../utils/uploadToCloudinary');

// @desc    Register user
// @route   POST /api/auth/register
// @access  Public
exports.registerUser = async (req, res) => {
  try {
    const { name, email, password, role } = req.body;

    // Only these roles may be self-assigned at registration.
    // 'admin' is intentionally excluded — admins must be created
    // directly in the database or via a separate admin-only endpoint.
    const ALLOWED_ROLES = ['surfer', 'owner', 'guide'];
    const assignedRole = ALLOWED_ROLES.includes(role) ? role : 'surfer';

    // Check if user exists
    const userExists = await User.findOne({ email });

    if (userExists) {
      return res.status(400).json({
        success: false,
        message: 'User already exists'
      });
    }

    // Create user
    const user = await User.create({
      name,
      email,
      password,
      role: assignedRole
    });

    if (user) {
      res.status(201).json({
        success: true,
        data: {
          _id: user._id,
          name: user.name,
          email: user.email,
          role: user.role,
          isVerified: user.isVerified,
          token: generateToken(user._id)
        }
      });
    }
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message
    });
  }
};

// @desc    Login user
// @route   POST /api/auth/login
// @access  Public
exports.loginUser = async (req, res) => {
  try {
    const { email, password } = req.body;

    // Check for user email
    const user = await User.findOne({ email }).select('+password');

    if (!user) {
      return res.status(401).json({
        success: false,
        message: 'Invalid credentials'
      });
    }

    // Check if password matches
    const isMatch = await user.matchPassword(password);

    if (!isMatch) {
      return res.status(401).json({
        success: false,
        message: 'Invalid credentials'
      });
    }

    res.json({
      success: true,
      data: {
        _id: user._id,
        name: user.name,
        email: user.email,
        role: user.role,
        isVerified: user.isVerified,
        token: generateToken(user._id)
      }
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message
    });
  }
};

// @desc    Upload certificate
// @route   POST /api/auth/upload-certificate
// @access  Private
exports.uploadCertificate = async (req, res) => {
  try {
    if (!req.file) {
      return res.status(400).json({
        success: false,
        message: 'Please upload a certificate'
      });
    }

    // Upload buffer directly to Cloudinary — no temp file on disk
    const result = await uploadToCloudinary(req.file.buffer, {
      folder: 'zurf/certificates',
      resource_type: 'auto',
    });

    // Update user with certificate URL
    const user = await User.findByIdAndUpdate(
      req.user._id,
      { certificate: result.secure_url },
      { new: true }
    );

    res.json({
      success: true,
      data: {
        certificate: user.certificate
      }
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message
    });
  }
};

// @desc    Get current user profile
